_META_ROUTER_SYMBOLS = (
    "DomainRouteResult",
    "route_problem",
    "get_supported_domains",
)


def __getattr__(name: str):  # noqa: D103
    if name in _META_ROUTER_SYMBOLS:
        from orpath.agents import meta_router as _meta_router

        return getattr(_meta_router, name)
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
