"""OR-Path agent-facing tool surface (LangChain ``@tool`` wrappers).

Re-exports the agent layers used across the product:

  * ``workers``    — the four permanent elite specialist factories (analyst /
    modeler / writer / reviewer) with ``create_*_agent`` factories accepting
    per-call ``cartridge_tools`` / ``domain_directive`` injections (Plan 1.3).
    The legacy standalone ``or_verifier`` factory remains only for the retired
    academic supervisor flow; number verification is now owned by the
    deterministic gates (Plan 1.4).
  * ``deterministic_nodes`` — LLM-free preflight probe and hard validation
    nodes (Plan 1.4).
  * ``adaptive_graph``     — Tier-A/B/C deterministic routing state machine
    over the four elite workers (Plan 1.5).
  * ``supervisor`` — the centralised supervisor that orchestrates those
    workers via ``langgraph_supervisor`` (legacy entry point).

Importing this package is offline-safe: graph construction uses
``orpath.control_plane.get_chat_model()`` which falls back to a placeholder
key when no credentials are configured.
"""
